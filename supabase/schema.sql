create table public.perfiles (
  id uuid primary key references auth.users (id) on delete cascade,
  correo text not null,
  creado_en timestamptz not null default now()
);

create table public.proveedores (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users (id) on delete cascade,
  nombre text not null,
  telefono text,
  correo text,
  creado_en timestamptz not null default now()
);

create table public.productos (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users (id) on delete cascade,
  nombre text not null,
  precio numeric(12, 2) not null check (precio >= 0),
  stock integer not null check (stock >= 0),
  proveedor_id bigint not null
    references public.proveedores (id) on update cascade on delete restrict,
  creado_en timestamptz not null default now()
);

create index productos_owner_id_idx on public.productos (owner_id);
create index productos_proveedor_id_idx on public.productos (proveedor_id);
create index proveedores_owner_id_idx on public.proveedores (owner_id);

alter table public.perfiles enable row level security;
alter table public.proveedores enable row level security;
alter table public.productos enable row level security;

revoke all on public.perfiles, public.proveedores, public.productos
  from anon, public;

create policy "Cada usuario consulta su perfil"
  on public.perfiles for select to authenticated
  using (id = (select auth.uid()));
create policy "Cada usuario actualiza su perfil"
  on public.perfiles for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

create policy "Cada usuario administra sus proveedores"
  on public.proveedores for all to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));

create policy "Cada usuario administra sus productos"
  on public.productos for all to authenticated
  using (owner_id = (select auth.uid()))
  with check (
    owner_id = (select auth.uid())
    and exists (
      select 1
      from public.proveedores as proveedor
      where proveedor.id = proveedor_id
        and proveedor.owner_id = (select auth.uid())
    )
  );

grant select, update on public.perfiles to authenticated;
grant select, insert, update, delete on public.proveedores to authenticated;
grant select, insert, update, delete on public.productos to authenticated;
grant usage, select on all sequences in schema public to authenticated;

create or replace function public.crear_perfil_usuario()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.perfiles (id, correo)
  values (new.id, new.email);
  return new;
end;
$$;

create trigger al_crear_usuario
  after insert on auth.users
  for each row execute procedure public.crear_perfil_usuario();

insert into public.perfiles (id, correo)
select id, email from auth.users
on conflict (id) do nothing;

revoke all on function public.crear_perfil_usuario() from public, anon, authenticated;

create or replace function public.eliminar_proveedor(
  p_supplier_id bigint,
  p_destination_id bigint default null
)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  associated_count integer;
begin
  if not exists (
    select 1 from public.proveedores
    where id = p_supplier_id and owner_id = (select auth.uid())
  ) then
    raise exception 'El proveedor no existe o no tienes acceso.';
  end if;

  select count(*) into associated_count
  from public.productos
  where proveedor_id = p_supplier_id and owner_id = (select auth.uid());

  if associated_count > 0 then
    if p_destination_id is null or p_destination_id = p_supplier_id then
      raise exception 'Selecciona otro proveedor para transferir los productos.';
    end if;
    if not exists (
      select 1 from public.proveedores
      where id = p_destination_id and owner_id = (select auth.uid())
    ) then
      raise exception 'El proveedor de destino no existe o no tienes acceso.';
    end if;

    update public.productos
    set proveedor_id = p_destination_id
    where proveedor_id = p_supplier_id and owner_id = (select auth.uid());
  end if;

  delete from public.proveedores
  where id = p_supplier_id and owner_id = (select auth.uid());
end;
$$;

grant execute on function public.eliminar_proveedor(bigint, bigint) to authenticated;
revoke all on function public.eliminar_proveedor(bigint, bigint) from public, anon;
